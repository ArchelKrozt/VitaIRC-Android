#!/usr/bin/env python3
"""Generates app/src/main/java/.../L.kt: Spanish UI text -> English.

The table is tools/strings_vita.py (the texts shared with VitaIRC for PS Vita) plus
tools/strings_android.py (the texts only the Android app has)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
table = {}
for name in ('strings_vita.py', 'strings_android.py'):
    ns = {}
    exec(open(os.path.join(here, name), encoding='utf-8').read(), ns)
    table.update(ns['T'])

def kt(s):   # the table holds C string contents: \" and \\ work the same in Kotlin
    return '"' + s.replace('$', '\\$') + '"'

out = ['// Generated by tools/gen_strings.py: Spanish source strings -> English. Do not edit.',
       'package io.github.archelkrozt.vitairc', '',
       'object L {',
       '    @Volatile var english = false',
       '    fun t(es: String): String = if (english) en[es] ?: es else es',
       '    private val en: Map<String, String> = HashMap<String, String>(%d).apply {' % (len(table) * 2)]
for k, v in table.items():
    out.append('        put(%s, %s)' % (kt(k), kt(v)))
out += ['    }', '}', '']
dst = os.path.join(here, '..', 'app', 'src', 'main', 'java', 'io', 'github', 'archelkrozt', 'vitairc', 'L.kt')
open(dst, 'w', encoding='utf-8').write('\n'.join(out))
print(len(table), 'strings')
